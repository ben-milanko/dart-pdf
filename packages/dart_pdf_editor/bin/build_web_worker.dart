// Builds a self-hosted Web Worker bundle for dart_pdf_editor's off-thread page
// renderer, so apps that want a custom worker URL don't have to hand-write a
// worker entry or remember the exact `dart compile js` invocation.
//
// Most Flutter web apps do not need this command: the optional
// dart_pdf_editor_assets package ships a prebuilt worker, and
// registerBundledEditorAssets() wires it up. Use this only to self-host a
// custom worker URL.
//
// Run it from your app's root (where pubspec.yaml lives):
//
//   dart run dart_pdf_editor:build_web_worker
//
// It generates a tiny worker entry under .dart_tool/ and compiles it to
// `web/pdf_render_worker.dart.js`, which `flutter build web` then serves next
// to index.html. Point the app at that custom bundle by setting (on web):
//
//   pdfRenderWorkerScriptUrl = 'pdf_render_worker.dart.js';
//
// You can commit the produced `web/pdf_render_worker.dart.js` and only re-run
// this when you upgrade dart_pdf_editor - it does NOT have to run every build.
// See doc/render_worker_web.md in the repo for the full picture.
import 'dart:io';

const _entryName = 'pdf_render_worker.dart';
const _defaultOut = 'web/pdf_render_worker.dart.js';

/// The dart2js optimization level the worker is compiled at by default.
///
/// -O3 is -O2 plus `--omit-implicit-checks`: it drops the implicit parameter
/// and covariance checks dart2js otherwise emits on every generic `List` store,
/// `add` and `setRange`, which were a large share of the worker's
/// interpret/extract/inflate time. Bounds checks stay, so the parsers'
/// `on RangeError` recovery still works. pdf_cos, pdf_document and
/// pdf_graphics analyze with `strict-casts` so no code there can depend on an
/// implicit downcast being checked.
///
/// Not -O4 (what `flutter build web --release` uses for the app itself): its
/// `--trust-primitives` makes an out-of-range typed-array read yield
/// `undefined` instead of throwing, so a scan loop that relies on the
/// RangeError to stop could spin on hostile bytes. That needs a
/// fuzz/truncation smoke over broken files, with timeouts, first.
const defaultWorkerOptimizationLevel = 3;

const _entrySource = '''
// GENERATED by `dart run dart_pdf_editor:build_web_worker` - do not edit.
// The dedicated Web Worker entry for the off-thread PDF page renderer.
import 'package:dart_pdf_editor/render_worker_web.dart';

void main() => runPdfRenderWorker();
''';

// `dart run` ignores main's return value, so the status goes through exitCode;
// otherwise a failed dart2js compile exits 0 and the CI step running it passes.
Future<void> main(List<String> args) async => exitCode = await _build(args);

Future<int> _build(List<String> args) async {
  if (args.contains('-h') || args.contains('--help')) {
    stdout.writeln(_usage);
    return 0;
  }

  final WorkerBuildOptions options;
  try {
    options = WorkerBuildOptions.parse(args);
  } on FormatException catch (e) {
    stderr.writeln('error: ${e.message}\n');
    stderr.writeln(_usage);
    return 64;
  }
  final out = options.out;

  // Must run from an app root that depends on dart_pdf_editor.
  if (!File('pubspec.yaml').existsSync()) {
    stderr.writeln(
      'error: run this from your app root (where pubspec.yaml lives).',
    );
    return 64;
  }
  // The package config can live above cwd (pub workspaces keep one at the
  // workspace root), so walk up to find it - the same search Dart itself does.
  final packageConfig = _findPackageConfig(Directory.current);
  if (packageConfig == null) {
    stderr.writeln(
      'error: no .dart_tool/package_config.json found - run '
      '`flutter pub get` first.',
    );
    return 64;
  }
  if (!packageConfig.readAsStringSync().contains('"dart_pdf_editor"')) {
    stderr.writeln(
      'error: this project does not depend on dart_pdf_editor - add it to '
      'pubspec.yaml\n       and run `flutter pub get` first.',
    );
    return 64;
  }

  // Generate the worker entry beside the package config's .dart_tool, so it
  // never clutters the app's own web/ sources - only the compiled .js lands in
  // web/.
  final entryDir = Directory('${packageConfig.parent.path}/dart_pdf_editor')
    ..createSync(recursive: true);
  final entry = File('${entryDir.path}/$_entryName')
    ..writeAsStringSync(_entrySource);

  Directory(_dirOf(out)).createSync(recursive: true);

  final cmd = [
    'compile',
    'js',
    ...options.compilerFlags,
    '--packages=${packageConfig.path}',
    '-o',
    out,
    entry.path,
  ];

  final dart = Platform.resolvedExecutable;
  stdout.writeln('==> $dart ${cmd.join(' ')}');
  final result = await Process.start(
    dart,
    cmd,
    mode: ProcessStartMode.inheritStdio,
  );
  final code = await result.exitCode;
  if (code != 0) {
    stderr.writeln('error: worker compile failed (exit $code).');
    return code;
  }

  stdout.writeln('''
==> Built $out

For the normal path, depend on dart_pdf_editor_assets and call
registerBundledEditorAssets() at startup - it points the worker at that
package's bundled asset, so no per-URL setup is needed.

To use this custom app-hosted worker instead, set this once in your app's
main() (web only):

    import 'package:dart_pdf_editor/dart_pdf_editor.dart';
    import 'package:flutter/foundation.dart';

    void main() {
      if (kIsWeb) {
        pdfRenderWorkerScriptUrl = '${_webUrlForOut(out)}';
      }
      runApp(...);
    }

Then `flutter build web` serves the custom worker from $out. You can commit it
and only re-run this tool when you upgrade dart_pdf_editor.''');
  return 0;
}

/// The parsed command line. Kept apart from the build so the flag handling
/// (and the default optimization level in particular) is testable without
/// running dart2js.
class WorkerBuildOptions {
  WorkerBuildOptions({
    this.out = _defaultOut,
    this.optimizationLevel = defaultWorkerOptimizationLevel,
    this.sourceMaps = false,
  });

  /// Parses [args]; `-h`/`--help` is checked before this. A bad flag throws a
  /// [FormatException] whose message is the user-facing error.
  factory WorkerBuildOptions.parse(List<String> args) {
    var out = _defaultOut;
    int? level = defaultWorkerOptimizationLevel;
    var sourceMaps = false;
    for (var i = 0; i < args.length; i++) {
      final arg = args[i];
      if (arg == '--out' || arg == '-o') {
        if (i + 1 >= args.length) throw FormatException('$arg needs a path');
        out = args[++i];
      } else if (arg.startsWith('--out=')) {
        out = arg.substring('--out='.length);
      } else if (arg == '--optimization-level') {
        if (i + 1 >= args.length) throw FormatException('$arg needs a level');
        level = _parseLevel(arg, args[++i]);
      } else if (arg.startsWith('--optimization-level=')) {
        level = _parseLevel(
          arg,
          arg.substring('--optimization-level='.length),
        );
      } else if (arg.startsWith('-O')) {
        level = _parseLevel(arg, arg.substring('-O'.length));
      } else if (arg == '--no-optimize') {
        level = null;
      } else if (arg == '--source-maps') {
        sourceMaps = true;
      } else {
        throw FormatException('unknown argument "$arg"');
      }
    }
    return WorkerBuildOptions(
      out: out,
      optimizationLevel: level,
      sourceMaps: sourceMaps,
    );
  }

  /// Output JS path.
  final String out;

  /// The dart2js `-O` level (1-4), or null for `--no-optimize`, which passes
  /// no `-O` flag at all (dart2js's own default, -O1).
  final int? optimizationLevel;

  /// Whether to emit a `.js.map` beside the worker.
  final bool sourceMaps;

  /// The `dart compile js` flags these options add (paths excluded).
  List<String> get compilerFlags => [
        if (optimizationLevel != null) '-O$optimizationLevel',
        if (!sourceMaps) '--no-source-maps',
      ];

  static int _parseLevel(String flag, String value) {
    final level = int.tryParse(value);
    if (level == null || level < 1 || level > 4) {
      throw FormatException('$flag takes a level from 1 to 4, not "$value"');
    }
    return level;
  }
}

/// Walks up from [start] looking for `.dart_tool/package_config.json`, the way
/// the Dart toolchain resolves packages - so this works from a plain app root
/// (config in the app) and from inside a pub workspace (config at the root).
File? _findPackageConfig(Directory start) {
  for (var dir = start;; dir = dir.parent) {
    final candidate = File('${dir.path}/.dart_tool/package_config.json');
    if (candidate.existsSync()) return candidate;
    if (dir.path == dir.parent.path) return null; // reached the filesystem root
  }
}

String _dirOf(String path) {
  final i = path.lastIndexOf('/');
  return i <= 0 ? '.' : path.substring(0, i);
}

String _basename(String path) {
  final i = path.lastIndexOf('/');
  return i < 0 ? path : path.substring(i + 1);
}

String _webUrlForOut(String path) {
  final normalized = path.replaceAll('\\', '/');
  return normalized.startsWith('web/')
      ? normalized.substring('web/'.length)
      : _basename(normalized);
}

